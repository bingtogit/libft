#include "libft.h"

size_t	ft_strlcat(char *dst, const char *src, size_t size)
{
	size_t i;
	size_t j;
	size_t srclen;

	j = 0;
	i = 0;
	srclen = ft_strlen(src);

	while (i < size && dst[i])
		i++;
	if (i == size)
		return (size + srclen);
	while (i + j < size - 1 && src[j])
	{
		dst[i + j] = src[j];
		j++;
	}
	dst[i + j] = '\0';
	return (i + srclen);
}