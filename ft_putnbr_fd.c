#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	char	s[12];
	int		i;
	long	nb;

	nb = n;
	if (nb < 0)
		nb = -nb;
	i = 12;
	if (nb == 0)
		s[--i] = '0';
	while (nb > 0)
	{
		s[--i] = nb % 10 + '0';
		nb /= 10;
	}
	if (n < 0)
		s[--i] = '-';
	write(fd, &s[i], 12 - i);
}
